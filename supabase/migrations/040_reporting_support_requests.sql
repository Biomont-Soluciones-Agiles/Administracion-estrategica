-- Solicitudes de responsable de apoyo para el registro de mediciones.
-- Un gerente responsable propone un apoyo; GCG revisa y, al aprobar,
-- la persona recibe rol Usuario y acceso únicamente a esa asignación de sede.
begin;

alter table public.indicator_change_requests
  add column if not exists requested_email text;

alter table public.indicator_change_requests
  drop constraint if exists indicator_change_requests_kind_check;

alter table public.indicator_change_requests
  add constraint indicator_change_requests_kind_check
  check (kind in ('target', 'report', 'delete_report', 'definition', 'assign_support'));

create table if not exists public.indicator_reporting_supports (
  id bigint generated by default as identity primary key,
  site_assignment_id bigint not null references public.indicator_site_assignments(id) on delete cascade,
  support_email text not null,
  active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (site_assignment_id, support_email)
);

create index if not exists indicator_reporting_supports_active_idx
  on public.indicator_reporting_supports(site_assignment_id, active);

alter table public.indicator_reporting_supports enable row level security;
drop policy if exists "Read reporting supports" on public.indicator_reporting_supports;
drop policy if exists "GCG manages reporting supports" on public.indicator_reporting_supports;
create policy "Read reporting supports"
  on public.indicator_reporting_supports for select to authenticated using (true);
create policy "GCG manages reporting supports"
  on public.indicator_reporting_supports for all to authenticated
  using (public.is_gcg()) with check (public.is_gcg());

create or replace function public.can_report_site_indicator(indicator bigint, assignment bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select auth.uid() is not null and (
    public.is_gcg()
    or public.is_super_admin()
    or exists (
      select 1
      from public.indicator_site_assignments a
      where a.id = assignment
        and a.indicator_id = indicator
        and a.active
        and public.person_matches(a.responsible_email)
    )
    or exists (
      select 1
      from public.indicator_reporting_supports s
      join public.indicator_site_assignments a on a.id = s.site_assignment_id
      where s.site_assignment_id = assignment
        and s.active
        and a.indicator_id = indicator
        and a.active
        and public.person_matches(s.support_email)
    )
  );
$$;

create or replace function public.prepare_indicator_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  i public.indicators;
  r public.indicator_reports;
  requester_email text;
  support_email text;
begin
  select * into strict i from public.indicators where id = new.indicator_id;
  new.requested_email := lower(auth.jwt() ->> 'email');

  if new.kind = 'target' then
    if new.proposed - array['target','comparator'] <> '{}'::jsonb
      or new.proposed->>'target' is null
      or new.proposed->>'comparator' is null
      or new.proposed->>'comparator' not in ('>','>=','=','<=','<') then
      raise exception 'Propuesta de meta inválida';
    end if;
    perform (new.proposed->>'target')::numeric;
    new.previous = jsonb_build_object('target', i.target, 'comparator', i.comparator);

  elsif new.kind = 'report' then
    select * into strict r from public.indicator_reports
    where id = new.report_id and indicator_id = new.indicator_id;
    if new.proposed - array['result','measurement_target','measurement_comparator'] <> '{}'::jsonb
      or new.proposed->>'result' is null then
      raise exception 'Resultado inválido';
    end if;
    perform (new.proposed->>'result')::numeric;
    if r.measurement_target is null then
      if new.proposed->>'measurement_target' is null
        or new.proposed->>'measurement_comparator' is null
        or new.proposed->>'measurement_comparator' not in ('>','>=','=','<=','<') then
        raise exception 'Indica la meta histórica para que GCG la verifique';
      end if;
      perform (new.proposed->>'measurement_target')::numeric;
    elsif new.proposed ? 'measurement_target' or new.proposed ? 'measurement_comparator' then
      raise exception 'La meta histórica registrada no se puede cambiar';
    end if;
    new.previous = jsonb_build_object('result', r.result);

  elsif new.kind = 'delete_report' then
    select * into strict r from public.indicator_reports
    where id = new.report_id and indicator_id = new.indicator_id;
    if new.proposed - 'period' <> '{}'::jsonb then
      raise exception 'Solicitud de eliminación inválida';
    end if;
    new.previous = jsonb_build_object('result', r.result, 'period', r.period);

  elsif new.kind = 'assign_support' then
    requester_email := lower(auth.jwt() ->> 'email');
    support_email := lower(trim(new.proposed->>'support_email'));

    if new.proposed - 'support_email' <> '{}'::jsonb
      or support_email = ''
      or position('@' in support_email) = 0 then
      raise exception 'Responsable de apoyo inválido';
    end if;
    if requester_email = support_email then
      raise exception 'El responsable de apoyo debe ser otra persona';
    end if;
    if not public.can_manage_reporting(new.indicator_id) then
      raise exception 'Solo el gerente responsable puede solicitar un apoyo';
    end if;
    if not exists (
      select 1 from public.organization_people
      where lower(email) = support_email and active
    ) and not exists (
      select 1 from public.profiles
      where lower(email) = support_email
    ) then
      raise exception 'La persona de apoyo debe tener acceso a BIOMET';
    end if;
    new.previous = '{}'::jsonb;

  else
    if new.proposed - 'name' <> '{}'::jsonb
      or coalesce(length(trim(new.proposed->>'name')), 0) = 0 then
      raise exception 'Nombre inválido';
    end if;
    new.previous = jsonb_build_object('name', i.name);
  end if;

  return new;
end;
$$;

create or replace function public.review_indicator_change(
  request_id bigint,
  approve boolean,
  review_comment text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  q public.indicator_change_requests;
  i public.indicators;
  r public.indicator_reports;
  assignment_id bigint;
  support_email text;
  requester_email text;
begin
  if not public.is_gcg() then
    raise exception 'Solo GCG puede revisar solicitudes';
  end if;

  if not approve and coalesce(length(trim(review_indicator_change.review_comment)), 0) = 0 then
    raise exception 'Ingresa un comentario al rechazar la solicitud';
  end if;

  select * into strict q
  from public.indicator_change_requests
  where id = request_id
  for update;

  if q.status <> 'Pendiente' then
    raise exception 'La solicitud ya fue revisada';
  end if;

  if approve then
    select * into strict i from public.indicators where id = q.indicator_id for update;

    if q.kind = 'target' then
      if q.previous <> jsonb_build_object('target', i.target, 'comparator', i.comparator) then
        raise exception 'La meta cambió desde la solicitud. Envía otra solicitud.';
      end if;
      insert into public.indicator_target_history(indicator_id, target, comparator, changed_by)
      values (i.id, i.target, i.comparator, auth.uid());
      update public.indicators
      set target = (q.proposed->>'target')::numeric,
          comparator = q.proposed->>'comparator',
          updated_at = now()
      where id = i.id;

    elsif q.kind = 'report' then
      select * into strict r from public.indicator_reports where id = q.report_id for update;
      if q.previous->>'result' <> r.result::text then
        raise exception 'La medición cambió desde la solicitud';
      end if;
      update public.indicator_reports
      set result = (q.proposed->>'result')::numeric,
          measurement_target = coalesce(r.measurement_target, (q.proposed->>'measurement_target')::numeric),
          measurement_comparator = coalesce(r.measurement_comparator, q.proposed->>'measurement_comparator'),
          updated_at = now()
      where id = r.id;

    elsif q.kind = 'delete_report' then
      update public.indicator_change_requests as request
      set report_id = null,
          status = case
            when request.id = q.id then 'Aprobado'
            when request.status = 'Pendiente' then 'Rechazado'
            else request.status
          end,
          reviewed_by = case when request.status = 'Pendiente' then auth.uid() else request.reviewed_by end,
          reviewed_at = case when request.status = 'Pendiente' then now() else request.reviewed_at end,
          review_comment = case
            when request.id = q.id then nullif(trim(review_indicator_change.review_comment), '')
            when request.status = 'Pendiente' then coalesce(request.review_comment, 'Solicitud cerrada porque se aprobó eliminar su medición asociada.')
            else request.review_comment
          end
      where request.report_id = q.report_id;

      delete from public.indicator_reports where id = q.report_id;
      return;

    elsif q.kind = 'assign_support' then
      support_email := lower(trim(q.proposed->>'support_email'));
      requester_email := lower(trim(q.requested_email));

      select a.id into assignment_id
      from public.indicator_site_assignments a
      where a.indicator_id = i.id
        and a.active
        and lower(a.responsible_email) = requester_email
      limit 1;

      if assignment_id is null then
        raise exception 'La persona solicitante no es responsable de una sede de este indicador';
      end if;

      insert into public.indicator_reporting_supports (
        site_assignment_id, support_email, active, created_by
      )
      values (assignment_id, support_email, true, q.requested_by)
      on conflict (site_assignment_id, support_email)
      do update set active = true, updated_at = now();

      insert into public.role_assignments(email, role)
      values (support_email, 'usuario')
      on conflict (email)
      do update set role = excluded.role, updated_at = now();

      update public.profiles
      set role = 'usuario'
      where lower(email) = support_email;

      update public.organization_people
      set role = 'usuario'
      where lower(email) = support_email;

    else
      if q.previous <> jsonb_build_object('name', i.name) then
        raise exception 'El nombre cambió desde la solicitud';
      end if;
      update public.indicators
      set name = q.proposed->>'name',
          updated_at = now()
      where id = i.id;
    end if;
  end if;

  update public.indicator_change_requests as request
  set status = case when approve then 'Aprobado' else 'Rechazado' end,
      reviewed_by = auth.uid(),
      reviewed_at = now(),
      review_comment = nullif(trim(review_indicator_change.review_comment), '')
  where request.id = q.id;
end;
$$;

revoke all on function public.review_indicator_change(bigint, boolean, text) from public;
grant execute on function public.review_indicator_change(bigint, boolean, text) to authenticated;

notify pgrst, 'reload schema';
commit;
