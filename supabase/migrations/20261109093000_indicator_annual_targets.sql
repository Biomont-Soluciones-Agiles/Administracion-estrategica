-- Metas independientes por indicador y año. La meta existente del indicador queda
-- como respaldo para años que aún no tengan una meta anual definida.
begin;

create table if not exists public.indicator_annual_targets (
  id bigint generated by default as identity primary key,
  indicator_id bigint not null references public.indicators(id) on delete cascade,
  target_year integer not null check (target_year between 2000 and 2100),
  target numeric not null,
  comparator text not null check (comparator in ('>', '>=', '=', '<=', '<')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (indicator_id, target_year)
);

create index if not exists indicator_annual_targets_lookup_idx
  on public.indicator_annual_targets(indicator_id, target_year);

alter table public.indicator_annual_targets enable row level security;
drop policy if exists "Read annual indicator targets" on public.indicator_annual_targets;
drop policy if exists "GCG manages annual indicator targets" on public.indicator_annual_targets;
create policy "Read annual indicator targets" on public.indicator_annual_targets
  for select to authenticated using (true);
create policy "GCG manages annual indicator targets" on public.indicator_annual_targets
  for all to authenticated using (public.is_gcg()) with check (public.is_gcg());

create or replace function public.indicator_target_for_year(indicator bigint, target_year integer)
returns table(target numeric, comparator text)
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(annual.target, i.target), coalesce(annual.comparator, i.comparator)
  from public.indicators i
  left join public.indicator_annual_targets annual
    on annual.indicator_id = i.id and annual.target_year = $2
  where i.id = $1;
$$;

create or replace function public.set_indicator_annual_target(
  indicator bigint,
  target_year integer,
  target_value numeric,
  target_comparator text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_gcg() then
    raise exception 'Solo GCG puede definir metas anuales';
  end if;
  if target_year not between 2000 and 2100
    or target_value is null
    or target_comparator not in ('>', '>=', '=', '<=', '<') then
    raise exception 'Meta anual inválida';
  end if;
  if not exists (select 1 from public.indicators where id = indicator) then
    raise exception 'Indicador no encontrado';
  end if;

  insert into public.indicator_annual_targets(indicator_id, target_year, target, comparator, created_by)
  values (indicator, target_year, target_value, target_comparator, auth.uid())
  on conflict (indicator_id, target_year) do update
  set target = excluded.target,
      comparator = excluded.comparator,
      updated_at = now();

  -- Si ya existen mediciones de ese año, la meta anual se aplica a todo el año.
  update public.indicator_reports r
  set measurement_target = target_value,
      measurement_comparator = target_comparator,
      status = case when r.result is null then 'Sin datos'
        else public.measurement_status(r.result, target_value, target_comparator) end,
      updated_at = now()
  where r.indicator_id = indicator
    and extract(year from public.indicator_period_date(r.period)) = target_year;
end;
$$;

create or replace function public.prepare_measurement()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  i public.indicators;
  annual_target numeric;
  annual_comparator text;
  period_year integer;
begin
  select * into strict i from public.indicators where id = new.indicator_id for update;
  if tg_op = 'INSERT' and exists (
    select 1 from public.indicator_reports r
    where r.indicator_id = new.indicator_id
      and coalesce(r.site_assignment_id, 0) = coalesce(new.site_assignment_id, 0)
      and public.indicator_period_date(r.period) = public.indicator_period_date(new.period)
  ) then
    raise exception 'Este periodo ya fue registrado para esta sede.';
  end if;

  period_year := extract(year from public.indicator_period_date(new.period));
  select target, comparator into annual_target, annual_comparator
  from public.indicator_annual_targets
  where indicator_id = i.id and target_year = period_year;

  if tg_op = 'INSERT' then
    new.measurement_target = coalesce(annual_target, i.target);
    new.measurement_comparator = coalesce(annual_comparator, i.comparator);
  else
    new.measurement_target = coalesce(old.measurement_target, new.measurement_target, annual_target, i.target);
    new.measurement_comparator = coalesce(old.measurement_comparator, new.measurement_comparator, annual_comparator, i.comparator);
  end if;
  new.status = case when new.result is null then 'Sin datos'
    else public.measurement_status(new.result, new.measurement_target, new.measurement_comparator) end;
  return new;
end;
$$;

revoke all on function public.set_indicator_annual_target(bigint, integer, numeric, text) from public, anon;
grant execute on function public.set_indicator_annual_target(bigint, integer, numeric, text) to authenticated;

notify pgrst, 'reload schema';
commit;
